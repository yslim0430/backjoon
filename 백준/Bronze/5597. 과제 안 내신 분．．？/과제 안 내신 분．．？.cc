#include <iostream>
#include <vector>

using namespace std;

/*
* 30명의 학생중 과제를 해오지 않은 학생의 번호를 출력하는 문제.
30의 크기를 갖는 배열 중, 28개의 입력을 받았을 때 입력으로 받지 않은 번호의
배열 원소를 작은 순으로 출력하는 문제.
*/

int main() {

	vector <int> arr(30);

	/*
	입력받은 번호의 배열 원소는 1로, 그렇지 않은 배열 원소는 0으로 두고, 0인 배열 원소의 번호만 출력하면 될 것 같음.
	반복문을 0부터 29까지 오름차순으로 돌리니까 작은순으로 출력도 깔끔하게 될 듯함.
	*/

	for (int i = 0; i < 28; i++) {		//과제를 해온 학생들은 1로 처리
		int student;
		cin >> student;
		arr[student - 1] = 1;
	}

	for (int j = 0; j < 30; j++) {		//과제를 해오지 않은 학생들(원소가 0인 배열들) 출력
		if (arr[j] == 0) {
			cout << j + 1 << " ";
		}
	}
}