#include <iostream>
#include <string>

using namespace std;

/*
문자열을 입력으로 받고, 문자열의 단어 갯수를 구하는 문제. 단어는 공백 한개로 구분되며, 
공백이 연속으로 나오는 경우는 없다,
*/

/*공백이 단어를 구분하는 단위라면, 공백의 개수를 센 다음 +1한 값이 단어의 개수일 것 같다.
for문으로 공백인지 아닌지를 확인하고, 변수 word를 만든 뒤 공백이면 +1을 하자.
그런데 처음과 마지막에 공백이 있을 수 있으니, 1번째 원소부터 (마지막원소 - 1번째)원소까지만 반복하자.*/
int main() {

	string S;
	getline(cin, S);
	
	int word = 1;		//공백 개수 + 1 = 단어 개수이므로, word를 1로 초기화
	for (int i = 1; i < S.length() - 1; i++) {		//가장 첫 공백은 무시해야 하므로(첫 공백도 포함할 시 공백 개수 = 단어 개수가 됨) i = 1부터 반복 시작, 마지막 원소 -1에서 반복 종료
		if (S[i] == ' ') {
			word++;
		}
	}
	if (S.empty() || S == " ") {		//만약 공백만 입력으로 들어오면, 0을 출력하고 프로그램 종료
		cout << "0" << endl;
		return 0;
	}

	cout << word << endl;
}