#include <iostream>
#include <vector>

using namespace std;

/*
배열 원소 10개를 입력받은 뒤, 각각 원소를 42로 나눈 나머지들 중
서로 다른 원소의 갯수를 구하는 문제.
*/


int main() {

	vector <int> arr(10);

	for (int i = 0; i < 10; i++) {		//배열 원소 입력받기
		cin >> arr[i];
	}

	for (int j = 0; j < 10; j++) {		//배열 원소 42로 나누기
		int temp = 0;
		temp = arr[j] % 42;
		arr[j] = temp;
	}
	

	/*
	서로 다른 배열 원소를 찾는 방법이 뭐가 있을까..
	temp 변수들을 만들어놓고 다르면 하나씩 추가??

	아니면 알고리즘때 배운 느낌으로 가보는 것도 좋을 것 같은데
	반복문 써서 1부터 N까지 봤을때 하나라도 같으면 추가 안하고
	2부터 N까지 봤을때 하나라도 같으면 추가 안하고?
	
	근데 1이랑 2랑 같은 숫자라면 중복이 될 수 있겠다...

	그럼 반복문 안의 반복문을 쓰면?
	1을 10까지 다 비교한다음 같은게 있으면 +1을 하는거지.
	그래서 0인 경우만 전체에서 +1을 하는?

	이것도 안됨.

	전체 10개에서 같은게 있는 갯수를 빼면??
	중복되는만큼 하나씩 날려버리면 어떨까
	반복문이 2개 필요하긴 할 것임
	1부터 10까지 비교하고 같은게 있으면 sum-- 후 break로 바로 다음.
	2부터 10까지 비교하고 반복이면 가능할 듯??
	*/


	int sum = 10;		//서로다른 원소 갯수, 초기값은 10

	for (int k = 0; k < 10; k++) {		//서로 다른 원소 비교하는 반복문 !!
		for (int v = k + 1; v < 10; v++) {
			if (arr[k] == arr[v]) {
				sum--;
				break;
			}
		}
	}

	cout << sum << " \n";
} 